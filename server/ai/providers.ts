// Provider layer. Two implementations behind one interface:
//  - demo: a scripted stand-in. It never pretends to be a real AI; every reply is labelled and mode is 'demo'.
//  - anthropic: calls the Anthropic Messages API from the SERVER only (the key never reaches the browser).
//    This adapter is implemented against the public API but has NOT been exercised against the live service in this build.
import type { Config } from '../config';

export interface AiCompletionRequest {
  agentId: string;
  system: string;
  messages: { role: 'user' | 'assistant'; content: string }[];
  maxTokens?: number;
  model?: string | null;
}
export interface AiCompletion { text: string; provider: string; model: string; mode: 'live' | 'demo' }

export interface AiRuntime {
  readonly provider: 'demo' | 'anthropic';
  complete(req: AiCompletionRequest): Promise<AiCompletion>;
}

export class AiProviderError extends Error {
  constructor(public code: 'provider_unavailable' | 'provider_rejected' | 'timeout', message: string) { super(message); }
}

const DEMO_NOTE = 'Demo mode: no AI model is connected to this FREEVERSE instance, so this is a scripted reply, not real AI.';
const DEMO_HINT: Record<string, string> = {
  athena: 'When connected I help with study plans, explaining ideas and finding sources. For now, browse Learn for guides, paths and quizzes.',
  atlas: 'When connected I help with CVs, interviews and career planning. For now, see Opportunities and the Mentor directory.',
  nova: 'When connected I’m a creative and reflective companion. For now, your private journal, goals and habits are available in Nova’s tools (if you turned them on).',
  aegis: 'When connected I help explain safety and moderation. For now, see the Safety page and use Report on any content.',
  sage: 'When connected I help explain the constitution, governance and policies. For now, read the Constitution and Governance pages.',
  pulse: 'When connected I offer non-diagnostic wellbeing support and habit ideas. I am not a doctor or therapist. If you are struggling, the Support page lists real help.',
  forge: 'When connected I help shape ideas into projects and businesses. For now, see Events and Opportunities for founder programmes.',
  echo: 'When connected I help write, rewrite and translate. For now, you can draft in the post composer.',
  compass: 'When connected I suggest next steps from your goals. For now, try Explore and your personalised feed.',
  'founder-ai': 'When connected, I analyse the platform and prepare proposals. For now I can only show findings computed directly from the database; nothing here is generated by a model.',
};

export function demoReply(agentId: string, lastUser: string): string {
  const hint = DEMO_HINT[agentId] ?? 'When a model is connected this specialist can help here.';
  const quote = lastUser.trim().replace(/\s+/g, ' ').slice(0, 140);
  return `${DEMO_NOTE}\n\nYou wrote: “${quote}”\n\n${hint}`;
}

export function createAiRuntime(config: Config, fetchImpl: typeof fetch = fetch): AiRuntime {
  if (config.ai.provider === 'anthropic' && config.ai.anthropicApiKey) {
    const key = config.ai.anthropicApiKey;
    return {
      provider: 'anthropic',
      async complete(req) {
        const model = req.model || config.ai.novaModel;
        let res: Response;
        try {
          res = await fetchImpl('https://api.anthropic.com/v1/messages', {
            method: 'POST',
            headers: { 'content-type': 'application/json', 'x-api-key': key, 'anthropic-version': '2023-06-01' },
            body: JSON.stringify({ model, max_tokens: req.maxTokens ?? 700, system: req.system, messages: req.messages }),
            signal: AbortSignal.timeout(30_000),
          });
        } catch (e) {
          throw new AiProviderError((e as Error).name === 'TimeoutError' ? 'timeout' : 'provider_unavailable', 'The AI service could not be reached.');
        }
        if (!res.ok) throw new AiProviderError(res.status >= 500 ? 'provider_unavailable' : 'provider_rejected', `The AI service returned an error (${res.status}).`);
        const j = (await res.json()) as { content?: { type: string; text?: string }[] };
        const text = (j.content ?? []).filter((b) => b.type === 'text').map((b) => b.text ?? '').join('').trim();
        if (!text) throw new AiProviderError('provider_unavailable', 'The AI service returned an empty reply.');
        return { text, provider: 'anthropic', model, mode: 'live' };
      },
    };
  }
  return {
    provider: 'demo',
    async complete(req) {
      const last = [...req.messages].reverse().find((m) => m.role === 'user')?.content ?? '';
      return { text: demoReply(req.agentId, last), provider: 'demo', model: 'scripted', mode: 'demo' };
    },
  };
}
