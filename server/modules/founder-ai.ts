const id = z.string().uuid();
const wf = async <T>(fn: () => Promise<T>): Promise<T> => {
  try { return await fn(); } catch (e) { if (e instanceof WorkflowError) { if (e.status === 403) throw forbidden(e.message, e.code); throw badRequest(e.message, undefined, e.code); } throw e; }
};

const findingView = (f: any) => ({ id: f.id, kind: f.kind, epistemic: f.epistemic, severity: f.severity, title: f.title, body: f.body, evidence: json(f.evidence, []), status: f.status, proposalId: f.proposal_id ?? null, createdAt: f.created_at, updatedAt: f.updated_at });
const msgView = (m: any): AiMessageView => ({ id: m.id, role: m.role, body: m.body, createdAt: m.created_at, meta: json(m.meta, {}) });

const EPISTEMIC_HELP = {
  verified_fact: 'Computed directly from this platform’s data.', observation: 'Something I noticed; it may have more than one explanation.',
  assumption: 'Something I am taking as true without proof.', forecast: 'A projection. It can be wrong.', suggestion: 'My recommendation. You decide.',
};

/** Builds the grounded context the Founder AI answers from. Aggregate facts only: never message, journal, Nova or private-profile content. */
async function groundedFacts(s: Services) {
  const o = await collectOverview(s);
  const findings = await s.db.query<any>("SELECT * FROM founder_ai_findings WHERE status = 'open' ORDER BY CASE severity WHEN 'high' THEN 0 WHEN 'medium' THEN 1 WHEN 'low' THEN 2 ELSE 3 END, created_at DESC LIMIT 12");
  return { o, findings: findings.map(findingView) };
}

/** Deterministic answer used when no AI model is connected. Clearly labelled; nothing here is generated by a model. */
function computedAnswer(question: string, g: Awaited<ReturnType<typeof groundedFacts>>): string {
  const q = question.toLowerCase();
  const lines: string[] = ['Computed answer (no AI model is connected; I am reading fixed facts from the database, not reasoning in free text).', ''];
  const pick = (keys: string[]) => g.o.platform.concat(g.o.moderation, g.o.security).filter((m) => keys.some((k) => m.key.includes(k)));
  let rows = [] as { label: string; value: string | number; note?: string }[];
  if (/moderat|report|case|safety/.test(q)) rows = g.o.moderation;
  else if (/secur|access|audit|risk/.test(q)) rows = g.o.security;
  else if (/member|user|growth|sign/.test(q)) rows = pick(['members', 'signups']);
  else if (/govern|council|seat/.test(q)) rows = g.o.governance.map((x) => ({ label: `${x.name} seats filled`, value: `${x.filled}/${x.seats}` }));
  else rows = g.o.platform.slice(0, 6);
  lines.push('Verified from the database:', ...rows.map((r) => `• ${r.label}: ${r.value}${r.note ? ` (${r.note})` : ''}`));
  if (g.findings.length) lines.push('', 'Open findings I would look at first:', ...g.findings.slice(0, 4).map((f: any) => `• [${f.epistemic.replace('_', ' ')}] ${f.title}`));
  lines.push('', 'I have not read any private content, and I have not executed anything. If you want a change, I can prepare a proposal for your approval.');
  return lines.join('\n');
}

export const founderAiModule: ModuleDef = {
  name: 'founder-ai',
  register(router, s) {
    router.get('/api/founder-ai/state', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const st = await founderAiSettings(c.db);
      const open = await c.db.get<{ n: number }>("SELECT COUNT(*) AS n FROM founder_ai_findings WHERE status = 'open'");
      const pending = await c.db.get<{ n: number }>("SELECT COUNT(*) AS n FROM proposals WHERE status = 'pending_approval'");
      return {
        mode: st.mode, modeLabel: AI_MODE_LABEL[st.mode], modes: AI_MODES.map((m) => ({ id: m, label: AI_MODE_LABEL[m], help: m === 'advisory' ? 'Only analyses and recommends. Nothing it prepares can be executed.' : m === 'approval_required' ? 'Default. It prepares changes and waits for your explicit approval.' : 'May run only routine low-risk actions inside rules you set. Everything else, and every high-impact action, still needs your approval.' })),
        rules: st.rules, ruleActions: RULE_ACTIONS.map((a) => ({ type: a, label: ACTIONS[a]!.label })),
        alwaysApproval: ['Constitutional and governance changes', 'Security-sensitive permission changes', 'Anything destructive or irreversible', 'Material privacy changes', 'Changes to the AI’s own boundaries (mode and rules)', 'Any other high-risk action'],
        provider: s.ai.provider,
        honesty: s.ai.provider === 'demo'
          ? 'DEMO: no AI model is connected. Findings come from fixed checks on your data. Conversation answers are computed summaries, not model reasoning.'
          : 'A model is connected. It is given aggregate facts only, and its text is labelled as model output. It cannot execute anything.',
        epistemic: EPISTEMIC_HELP, openFindings: Number(open?.n ?? 0), pendingProposals: Number(pending?.n ?? 0),
      };
    });

    // ───────── mode and rules (high-impact: step-up, recorded, enforced by authorization) ─────────
    const change = async (c: Ctx<any, any>, actionType: string, payload: unknown, title: string) => {
      await c.requireStepUp();
      const r = await wf(() => createProposal(s, { source: 'founder', requestedBy: c.me.userId, actionType, payload, title, rationale: (payload as any).reason }));
      const d = await wf(() => decide(s, r.id, { userId: c.me.userId, role: 'founder', canDecide: c.can('proposals.decide') }, 'approve', 'Changed directly by the Founder.'));
      if (d.status !== 'executed') throw conflict('That change could not be applied.', 'failed');
      return founderAiSettings(c.db);
    };
    router.post('/api/founder-ai/mode', { auth: { perm: 'ai.autonomy.manage' }, body: z.object({ mode: z.enum(AI_MODES), reason: z.string().trim().min(10).max(300) }).strict() }, async (c) => {
      const cur = await founderAiSettings(c.db);
      if (cur.mode === c.body.mode) throw conflict('That is already the current mode.', 'no_change');
      const st = await change(c, 'ai.set_mode', c.body, `Set Founder AI mode to ${AI_MODE_LABEL[c.body.mode]}`);
      return { mode: st.mode };
    });
    router.put('/api/founder-ai/rules', {
      auth: { perm: 'ai.autonomy.manage' },
      body: z.object({ rules: z.array(z.object({ id: z.string(), actionType: z.string(), maxPerDay: z.number(), enabled: z.boolean(), note: z.string().optional() })).max(10), reason: z.string().trim().min(10).max(300) }).strict(),
    }, async (c) => {
      const st = await change(c, 'ai.set_rules', c.body, 'Change Founder AI autonomy rules');
      return { rules: st.rules };
    });

    // ───────── analysis and findings ─────────
    router.post('/api/founder-ai/analyze', { auth: { perm: 'ai.founder.use' }, rate: { key: 'fai:analyze', limit: 20, windowMs: 3600_000 } }, async (c) => {
      const drafts = await runAnalyzers(s);
      const stored = await storeFindings(s, drafts);
      const actions: { findingId: string; outcome: string; reason: string; proposalId: string }[] = [];
      for (const f of stored.filter((x) => x.isNew && x.draft.propose)) {
        const r = await submitFromAi(s, { ...f.draft.propose!, rationale: f.draft.propose!.rationale ?? f.draft.title, evidence: f.draft.evidence.map((e) => ({ ...e, kind: f.draft.epistemic })) });
        await c.db.run("UPDATE founder_ai_findings SET proposal_id = $2, status = CASE WHEN $3 = 'executed' THEN 'converted' ELSE status END WHERE id = $1", [f.id, r.id, r.outcome]);
        actions.push({ findingId: f.id, outcome: r.outcome, reason: r.reason, proposalId: r.id });
      }
      await audit(c.db, { actorId: c.me.userId, actorRole: 'founder', action: 'founder_ai.analysis_run', meta: { findings: stored.length, actions: actions.length } }, c.now());
      const items = await c.db.query<any>("SELECT * FROM founder_ai_findings WHERE status = 'open' ORDER BY created_at DESC LIMIT 50");
      return { findings: items.map(findingView), newFindings: stored.filter((x) => x.isNew).length, actions };
    });

    router.get('/api/founder-ai/findings', { auth: { perm: 'ai.founder.use' }, query: z.object({ status: z.enum(['open', 'acknowledged', 'dismissed', 'converted']).default('open') }) }, async (c) => {
      const rows = await c.db.query<any>('SELECT * FROM founder_ai_findings WHERE status = $1 ORDER BY updated_at DESC LIMIT 100', [c.query.status]);
      return { items: rows.map(findingView) };
    });
    router.post('/api/founder-ai/findings/:id/:act', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const act = c.params.act;
      if (act !== 'acknowledge' && act !== 'dismiss' && act !== 'reopen') throw notFound();
      const status = act === 'acknowledge' ? 'acknowledged' : act === 'dismiss' ? 'dismissed' : 'open';
      const r = await c.db.run('UPDATE founder_ai_findings SET status = $2, updated_at = $3 WHERE id = $1', [id.safeParse(c.params.id).data ?? '', status, c.now().toISOString()]);
      if (!r.changes) throw notFound();
      return { ok: true };
    });

    // ───────── preparing proposals ─────────
    router.post('/api/founder-ai/proposals', {
      auth: { perm: 'ai.founder.use' },
      body: z.object({ actionType: z.string().max(60), payload: z.unknown(), title: z.string().trim().min(5).max(140), rationale: z.string().trim().max(1500).default(''), findingId: id.optional() }).strict(),
    }, async (c) => {
      // The Founder asks Founder AI to prepare it. The AI's authority is checked by the workflow, not by this request.
      const r = await wf(() => submitFromAi(s, { actionType: c.body.actionType, payload: c.body.payload, title: c.body.title, rationale: c.body.rationale }));
      if (c.body.findingId) await c.db.run("UPDATE founder_ai_findings SET proposal_id = $2, status = 'converted', updated_at = $3 WHERE id = $1", [c.body.findingId, r.id, c.now().toISOString()]);
      return created(r);
    });

    // ───────── conversations ─────────
    const own = async (c: Ctx<any, any>, cid: string) => {
      const r = await c.db.get<any>("SELECT * FROM ai_conversations WHERE id = $1 AND user_id = $2 AND agent_id = 'founder-ai'", [id.safeParse(cid).data ?? '', c.me.userId]);
      if (!r) throw notFound('Conversation not found.');
      return r;
    };
    router.get('/api/founder-ai/conversations', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const rows = await c.db.query<any>("SELECT * FROM ai_conversations WHERE user_id = $1 AND agent_id = 'founder-ai' ORDER BY updated_at DESC LIMIT 100", [c.me.userId]);
      return { items: rows.map((r) => ({ id: r.id, title: r.title, updatedAt: r.updated_at })) };
    });
    router.post('/api/founder-ai/conversations', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const cid = uuid(); const now = c.now().toISOString();
      await c.db.run("INSERT INTO ai_conversations (id, user_id, agent_id, title, created_at, updated_at) VALUES ($1,$2,'founder-ai','New conversation',$3,$3)", [cid, c.me.userId, now]);
      return created({ conversation: { id: cid, title: 'New conversation', updatedAt: now } });
    });
    router.get('/api/founder-ai/conversations/:id', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const conv = await own(c, c.params.id!);
      const msgs = await c.db.query<any>('SELECT * FROM ai_messages WHERE conversation_id = $1 ORDER BY created_at, id LIMIT 300', [conv.id]);
      return { conversation: { id: conv.id, title: conv.title, updatedAt: conv.updated_at }, messages: msgs.map(msgView) };
    });
    router.delete('/api/founder-ai/conversations/:id', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const conv = await own(c, c.params.id!);
      await c.db.run('DELETE FROM ai_conversations WHERE id = $1', [conv.id]);
      return { ok: true };
    });
    router.post('/api/founder-ai/conversations/:id/messages', { auth: { perm: 'ai.founder.use' }, body: z.object({ body: z.string().trim().min(1).max(3000) }).strict(), rate: { key: 'fai:chat', limit: 30, windowMs: 60_000 } }, async (c) => {
      const conv = await own(c, c.params.id!);
      const now = c.now().toISOString();
      const umid = uuid(); const amid = uuid();
      await c.db.run("INSERT INTO ai_messages (id, conversation_id, role, body, created_at) VALUES ($1,$2,'user',$3,$4)", [umid, conv.id, c.body.body, now]);
      const g = await groundedFacts(s);
      let text: string; let meta: AiMessageView['meta'];
      if (s.ai.provider === 'demo') { text = computedAnswer(c.body.body, g); meta = { mode: 'demo', provider: 'computed', agentId: 'founder-ai' }; }
      else {
        const prior = (await c.db.query<any>("SELECT role, body FROM ai_messages WHERE conversation_id = $1 AND role IN ('user','assistant') ORDER BY created_at, id", [conv.id])).map((m) => ({ role: m.role as 'user' | 'assistant', content: m.body })).slice(-12);
        const system = 'You are the Founder AI. Answer ONLY from the facts below. Label each statement as one of: verified fact, observation, assumption, forecast, suggestion. ' +
          'Never claim you inspected private data, read messages, or executed anything; you can only recommend, and changes go through the approval workflow. If a fact is not in the data, say you do not know.\n' +
          `FACTS (JSON, aggregate only):\n${JSON.stringify({ platform: g.o.platform, moderation: g.o.moderation, security: g.o.security, governance: g.o.governance, council: g.o.council, openFindings: g.findings.map((f: any) => ({ title: f.title, epistemic: f.epistemic })) })}`;
        const r = await wf(() => aiApi.callAgent(s, { agentId: 'founder-ai', userId: c.me.userId, messages: prior, system }));
        text = r.text; meta = { mode: r.mode, provider: r.provider, agentId: 'founder-ai' };
      }
      await c.db.run("INSERT INTO ai_messages (id, conversation_id, role, body, meta, created_at) VALUES ($1,$2,'assistant',$3,$4,$5)", [amid, conv.id, text, meta, c.now().toISOString()]);
      await c.db.run('UPDATE ai_conversations SET title = CASE WHEN title = $3 THEN $4 ELSE title END, updated_at = $2 WHERE id = $1', [conv.id, c.now().toISOString(), 'New conversation', c.body.body.slice(0, 48)]);
      const [u, a] = [await c.db.get('SELECT * FROM ai_messages WHERE id = $1', [umid]), await c.db.get('SELECT * FROM ai_messages WHERE id = $1', [amid])];
      return { userMessage: msgView(u), assistantMessage: msgView(a), labels: { demo: s.ai.provider === 'demo', executed: false } };
    });

    // ───────── coordination with the nine specialists ─────────
    router.post('/api/founder-ai/delegate', { auth: { perm: 'ai.founder.use' }, body: z.object({ to: z.string().max(40), title: z.string().trim().min(3).max(100), prompt: z.string().trim().min(5).max(2000) }).strict(), rate: { key: 'fai:delegate', limit: 20, windowMs: 3600_000 } }, async (c) => {
      if (c.body.to === 'founder-ai') throw badRequest('Choose one of the nine specialists.');
      const r = await delegate(s, { from: 'founder-ai', to: c.body.to, task: { title: c.body.title, prompt: c.body.prompt }, actorId: c.me.userId });
      await audit(c.db, { actorId: c.me.userId, actorRole: 'founder', action: 'founder_ai.delegated', targetType: 'ai_agent', targetId: c.body.to, outcome: r.status === 'completed' ? 'success' : 'failed' }, c.now());
      return { delegation: r };
    });

    router.get('/api/founder-ai/delegations', { auth: { perm: 'ai.founder.use' } }, async (c) => {
      const rows = await c.db.query<any>('SELECT * FROM ai_delegations ORDER BY created_at DESC LIMIT 50');
      return { items: rows.map((r) => ({ id: r.id, from: r.from_agent, to: r.to_agent, task: json(r.task, {}), status: r.status, result: json(r.result, null), createdAt: r.created_at })) };
    });

    // ───────── decision record ─────────
    router.get('/api/founder-ai/decisions', { auth: { perm: 'proposals.view' } }, async (c) => {
      const rows = await c.db.query<any>("SELECT id, title, source, action_type, effective_risk, status, decided_at, decision_note, auto_executed, executed_at, verification FROM proposals WHERE status <> 'pending_approval' ORDER BY COALESCE(decided_at, created_at) DESC LIMIT 100");
      return { items: rows.map((r) => ({ id: r.id, title: r.title, source: r.source, actionType: r.action_type, risk: r.effective_risk, status: r.status, decidedAt: r.decided_at, note: r.decision_note, autoExecuted: r.auto_executed === true || r.auto_executed === 1, executedAt: r.executed_at, verification: json(r.verification, null) })) };
    });
  },
};
