// Renders migrations/src/*.sql.tpl into plain SQL for each dialect.
//   node scripts/render-migrations.mjs          write migrations/postgres/*.sql and migrations/sqlite/*.sql
//   node scripts/render-migrations.mjs --check  fail if the committed files are out of date (used by the test suite)
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'migrations/src');

const TOKENS = {
  postgres: { ID: 'uuid', TS: 'timestamptz', JSON: 'jsonb', BOOL: 'boolean', NOW: 'now()', TRUE: 'true', FALSE: 'false' },
  sqlite: { ID: 'TEXT', TS: 'TEXT', JSON: 'TEXT', BOOL: 'INTEGER', NOW: "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))", TRUE: '1', FALSE: '0' },
};

export function renderOne(tpl, dialect) {
  const other = dialect === 'postgres' ? 'sqlite' : 'pg';
  const mine = dialect === 'postgres' ? 'pg' : 'sqlite';
  const out = [];
  let skipping = false;
  for (const line of tpl.split('\n')) {
    const t = line.trim();
    if (t.startsWith(`--@${other}-begin`)) { skipping = true; continue; }
    if (t.startsWith(`--@${other}-end`)) { skipping = false; continue; }
    if (skipping) continue;
    if (t.startsWith(`--@${mine}-begin`) || t.startsWith(`--@${mine}-end`)) continue;
    if (t.startsWith(`--@${other} `)) continue;
    if (t.startsWith(`--@${mine} `)) { out.push(line.replace(`--@${mine} `, '')); continue; }
    out.push(line);
  }
  let sql = out.join('\n').replace(/@([A-Z]+)\b/g, (m, k) => {
    if (!(k in TOKENS[dialect])) throw new Error(`Unknown token ${m}`);
    return TOKENS[dialect][k];
  });
  if (dialect === 'postgres') {
    const tables = [...sql.matchAll(/^CREATE TABLE (\w+)/gm)].map((m) => m[1]);
    sql += '\n-- Row level security: the application connects with a server-side role. Enabling RLS with no policies means\n' +
      '-- Supabase\'s auto-generated REST API (PostgREST) and the public anon key can read nothing from these tables.\n';
    for (const t of tables) sql += `ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY;\n`;
    sql += `DO $$ BEGIN\n  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN\n` +
      tables.map((t) => `    EXECUTE 'REVOKE ALL ON TABLE ${t} FROM anon';`).join('\n') + '\n  END IF;\n' +
      `  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN\n` +
      tables.map((t) => `    EXECUTE 'REVOKE ALL ON TABLE ${t} FROM authenticated';`).join('\n') + '\n  END IF;\nEND $$;\n';
  }
  return `-- GENERATED by scripts/render-migrations.mjs from migrations/src. Do not edit by hand.\n${sql}`;
}

export function renderAll() {
  const files = readdirSync(SRC).filter((f) => f.endsWith('.sql.tpl')).sort();
  const result = [];
  for (const f of files) {
    const tpl = readFileSync(join(SRC, f), 'utf8');
    const name = f.replace('.sql.tpl', '.sql');
    for (const dialect of ['postgres', 'sqlite']) result.push({ dialect, name, sql: renderOne(tpl, dialect) });
  }
  return result;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const { dialect, name, sql } of renderAll()) {
    const dir = join(root, 'migrations', dialect);
    const path = join(dir, name);
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== sql) { console.error(`STALE ${dialect}/${name}`); stale++; }
    } else { mkdirSync(dir, { recursive: true }); writeFileSync(path, sql); console.log(`wrote ${dialect}/${name}`); }
  }
  if (check && stale) process.exit(1);
}
